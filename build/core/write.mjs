/* ============================================================
   build/core/write.mjs · OWNER: Agent A (core engine)
   Assets and output: tokens.css checks, CSS partial concatenation + lint,
   asset copying, cache-bust hashes, the temp dir and the atomic swap.

   A build writes everything into docs.tmp/, the crawler checks it, and only
   then docs/ is replaced (rename). A failed build never touches docs/.
   ============================================================ */
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, existsSync, readdirSync, renameSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { hash8 } from "./util.mjs";
import { COLOR_LITERAL } from "./crawl.mjs";

/* ---------- tokens.css ---------- */
export function readTokens(siteDir, programIds, fail) {
  const file = join(siteDir, "css", "tokens.css");
  if (!existsSync(file)) { fail("site/css/tokens.css", "is missing"); return { out: "", light: "", dark: "", preload: [] }; }
  const src = readFileSync(file, "utf8");
  const block = (sel) => { const i = src.indexOf(sel); if (i < 0) return null; const a = src.indexOf("{", i), b = src.indexOf("}", a); return src.slice(a + 1, b); };
  const lightBlock = block(':root[data-theme="light"]');
  const darkBlock = block(':root[data-theme="dark"]');
  if (!lightBlock) fail("site/css/tokens.css", 'no :root[data-theme="light"] { … } block');
  if (!darkBlock) fail("site/css/tokens.css", 'no :root[data-theme="dark"] { … } block');
  const tc = (b) => ((b || "").match(/--theme-color:\s*(#[0-9a-fA-F]{3,8})/) || [])[1] || "";
  const light = tc(lightBlock), dark = tc(darkBlock);
  if (!light) fail("site/css/tokens.css", "--theme-color is missing from the light block");
  if (!dark) fail("site/css/tokens.css", "--theme-color is missing from the dark block");
  if (!/--fonts-href:/.test(src)) fail("site/css/tokens.css", "--fonts-href is missing (use none when fonts are self-hosted)");
  const preload = ((src.match(/--fonts-preload:\s*"([^"]*)"/) || [])[1] || "").split(/\s+/).filter(Boolean);
  for (const f of preload) if (!existsSync(join(siteDir, f))) fail("site/css/tokens.css", `--fonts-preload lists ${f}, but site/${f} does not exist`);
  for (const id of programIds) for (const suf of ["", "-tint", "-ink", "-on", "-edge"]) {
    for (const [name, b] of [["light", lightBlock], ["dark", darkBlock]]) {
      if (b && !new RegExp(`--prog-${id}${suf}:`).test(b)) fail("site/css/tokens.css", `--prog-${id}${suf} is missing from the ${name} block (every program needs its ink tokens)`);
    }
  }
  // readers without JS and a dark system setting: the dark block again (kept if tokens.css already has it)
  const hasNoJs = /@media \(prefers-color-scheme: dark\)\s*\{\s*:root:not\(\[data-theme\]\)/.test(src);
  const out = hasNoJs || !darkBlock ? src : `${src}\n/* generated by build: the Night edition for readers without JS */\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {${darkBlock}}\n}\n`;
  return { out, light, dark, preload, src };
}

/* ---------- CSS partials: concatenate + lint ---------- */
const DECL = /([a-z-]+)\s*:\s*([^;{}]+)(?=[;}])/g;
export function buildCss(siteDir, fail, warn) {
  const dir = join(siteDir, "css");
  const parts = readdirSync(dir).filter((f) => f.endsWith(".css") && f !== "tokens.css").sort();
  let css = "";
  for (const f of parts) {
    if (!/^\d\d-[a-z0-9-]+\.css$/.test(f)) fail(`site/css/${f}`, "partials are named NN-name.css");
    const src = readFileSync(join(dir, f), "utf8");
    const bare = src.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "));
    let m;
    DECL.lastIndex = 0;
    while ((m = DECL.exec(bare))) {
      const [, prop, val] = m;
      const line = bare.slice(0, m.index).split("\n").length;
      const v = val.replace(/var\(\s*--[\w-]+/g, "var(").replace(/--[\w-]+/g, "");
      if (!prop.startsWith("--") && COLOR_LITERAL.test(v)) fail(`site/css/${f}:${line}`, `color literal in "${prop}: ${val.trim().slice(0, 60)}" (colors live in tokens.css only)`);
      if (prop === "font-size") {
        const px = val.match(/^\s*(\d+(?:\.\d+)?)px\s*$/), rem = val.match(/^\s*(\d*\.?\d+)rem\s*$/);
        if ((px && +px[1] < 12) || (rem && +rem[1] < 0.75)) fail(`site/css/${f}:${line}`, `font-size ${val.trim()} is under the 12px floor`);
      }
    }
    css += `/* ---- ${f} ---- */\n${src.trimEnd()}\n`;
  }
  // undefined custom properties (a typo in a token name): warn
  const defined = new Set([...readFileSync(join(dir, "tokens.css"), "utf8").matchAll(/(--[\w-]+)\s*:/g), ...css.matchAll(/(--[\w-]+)\s*:/g)].map((x) => x[1]));
  const used = new Set([...css.matchAll(/var\(\s*(--[\w-]+)\s*\)/g)].map((x) => x[1]));
  const INLINE_ONLY = new Set(["--p", "--tick", "--a", "--s", "--b", "--f", "--ink-fill-2", "--map-ratio"]);
  for (const u of used) if (!defined.has(u) && !INLINE_ONLY.has(u)) warn("site/css", `var(${u}) is used but never defined`);
  return css;
}

/* ---------- files ---------- */
export function makeOut(dir) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const written = [];
  const write = (rel, data) => { const p = join(dir, rel); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, data); written.push(rel); };
  const copy = (from, rel) => { const p = join(dir, rel); mkdirSync(dirname(p), { recursive: true }); cpSync(from, p, { recursive: true }); };
  return { dir, write, copy, written };
}

/** Hash every file under a directory (sorted), for ?v= on the JS entry. */
export function hashDir(dir) {
  const acc = [];
  const walk = (d) => { for (const f of readdirSync(d).sort()) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else acc.push(f, readFileSync(p)); } };
  if (existsSync(dir)) walk(dir);
  return hash8(Buffer.concat(acc.map((x) => (typeof x === "string" ? Buffer.from(x) : x))));
}

/** Copy the static assets from site/ into docs.tmp/assets. */
export function copyAssets(out, siteDir) {
  for (const [from, to] of [["js", "assets/js"], ["fonts", "assets/fonts"], ["img", "assets/img"], ["map", "assets/map"]]) {
    if (existsSync(join(siteDir, from))) out.copy(join(siteDir, from), to);
  }
  out.copy(join(siteDir, "favicon.svg"), "assets/favicon.svg");
  const og = existsSync(siteDir) ? readdirSync(siteDir).filter((f) => /^og(-[a-z0-9-]+)?\.png$/.test(f)) : [];
  for (const f of og) out.copy(join(siteDir, f), `assets/${f}`);
  return new Set(og);
}

/** Replace docs/ with docs.tmp/ in two renames; the old copy is removed afterwards. */
export function swap(tmp, final) {
  const old = `${final}.old`;
  rmSync(old, { recursive: true, force: true });
  if (existsSync(final)) renameSync(final, old);
  renameSync(tmp, final);
  rmSync(old, { recursive: true, force: true });
}

/* ============================================================
   build/core/images.mjs · OWNER: Agent F (directory: people, art, partners)
   Landed by Agent A as a working stub (the path is core/ for import reasons;
   Agent F owns it). Reads data/images.json (generated by
   scripts/fetch-images.py) and renders <img> with explicit dimensions, or a
   fallback: monogram mug (people), text plate (orgs), halftone "Photo coming"
   (works). No inline colors: the frame takes its tint from [data-prog].

   API (engine spec §4.11, §5.2):
     makeImages(db) → { img, has, entry, mug, logo, photo }
     img(root, kind, id, { alt, cls, sizes, variant })  kind: "p" | "o" | "w"
     has(kind, id) · entry(kind, id) → manifest record · path(kind, id) → "assets/img/…" (root-relative)
     mug(root, person, { size: "s"|"m"|""|"l", alt, prog })  → .avatar (4:5) or .avatar.mono
     logo(root, org, { alt })                                 → <img> or .plate-text
     photo(root, work, { alt })                               → <img> or .photo.halftone
   ============================================================ */
import { esc, attr, initials } from "./util.mjs";

export function makeImages(db) {
  const M = db.images || {};
  const entry = (kind, id) => M[`${kind}/${id}`] || null;
  const has = (kind, id) => !!entry(kind, id);
  /** Site-root-relative URL of an image (the build copies site/img → docs/assets/img). */
  const path = (kind, id) => { const e = entry(kind, id); return e ? `assets/${e.file}` : null; };
  function img(root, kind, id, { alt = "", cls = "", sizes = "", lazy = true } = {}) {
    const e = entry(kind, id);
    if (!e) return "";
    return `<img${cls ? ` class="${cls}"` : ""} src="${attr(root + "assets/" + e.file)}" alt="${attr(alt)}" width="${e.w}" height="${e.h}"${lazy ? ' loading="lazy"' : ""} decoding="async"${sizes ? ` sizes="${attr(sizes)}"` : ""}>`;
  }
  const firstProg = (p) => (p.programs && p.programs[0]) || "also";
  function mug(root, person, { size = "", alt = "", prog, cls = "" } = {}) {
    const pr = prog || firstProg(person);
    const c = `avatar${size ? " " + size : ""}${cls ? " " + cls : ""}`;
    const i = img(root, "p", person.id, { alt });
    if (i) return `<span class="${c}" data-prog="${pr}">${i}</span>`;
    return `<span class="${c} mono halftone" data-prog="${pr}"${alt ? ` role="img" aria-label="${attr(alt)}"` : ""}><span aria-hidden="true">${esc(initials(person.name))}</span></span>`;
  }
  function logo(root, org, { alt } = {}) {
    const i = img(root, "o", org.id, { alt: alt ?? `${org.name} logo` });
    return i || `<span class="plate-text">${esc(org.name)}</span>`;
  }
  function photo(root, work, { alt = "" } = {}) {
    const i = img(root, "w", work.id, { alt });
    return i || `<span class="photo-missing label">Photo coming</span>`;
  }
  return { img, has, entry, path, mug, logo, photo };
}
